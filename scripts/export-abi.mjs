// Copies the compiled Equalship ABI from Foundry output into the web app.
import { readFileSync, writeFileSync } from "node:fs";

const artifact = JSON.parse(readFileSync("contracts/out/Equalship.sol/Equalship.json", "utf8"));
const body = JSON.stringify(artifact.abi, null, 2);
writeFileSync(
  "src/lib/equalshipAbi.ts",
  `// Generated by scripts/export-abi.mjs from contracts/src/Equalship.sol. Do not edit by hand.\nexport const equalshipAbi = ${body} as const;\n`,
);
console.log(`wrote ${artifact.abi.length} ABI entries`);
